package ISIMS.olive_connect.entity;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;

// US-24 [TEAM]: Equipment type added by the Logistics Manager (add-only: no rename or delete).
// Custom types only get the common equipment fields.
@Document(collection = "equipment_types")
public class CustomEquipmentType {

    @Id
    private String id;

    @Indexed(unique = true)
    private String code;

    private String label;
    private Instant createdAt;

    // Getters and Setters
    public String getId() { return id; }
    public void setId(String id) { this.id = id; }

    public String getCode() { return code; }
    public void setCode(String code) { this.code = code; }

    public String getLabel() { return label; }
    public void setLabel(String label) { this.label = label; }

    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
}
